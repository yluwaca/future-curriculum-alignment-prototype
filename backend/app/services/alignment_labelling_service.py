    @staticmethod
    def _cohens_kappa(first: list[int], second: list[int]) -> tuple[Optional[float], Optional[str]]:
        if len(first) < 2 or len(first) != len(second):
            return None, None
        categories = sorted({int(value) for value in first} | {int(value) for value in second})
        if len(categories) < 2:
            return None, "single_class"
        first_counts = Counter(first)
        second_counts = Counter(second)
        total = max(len(first), 1)
        observed = sum(1 for a, b in zip(first, second) if a == b) / total
        expected = sum(
            first_counts.get(category, 0) / total * second_counts.get(category, 0) / total
            for category in categories
        )
        if peek := (1.0 - expected):
            kappa = (observed - expected) / peek
        else:
            return None, "expected_agreement_unity"
        interpretations = [
            (0.81, "almost_perfect"),
            (0.61, "substantial"),
            (0.41, "moderate"),
            (0.21, "fair"),
            (0.0, "slight"),
            (-1.0, "poor"),
        ]
        interpretation = next(
            (name for bound, name in interpretations if kappa >= bound),
            "poor",
        )
        return round(float(kappa), 4), interpretation

    @staticmethod
    def _confusion_table(first: list[int], second: list[int]) -> Dict[str, Any]:
        total = len(first)
        if not total:
            return {"labels": [], "cell_totals": {}, "row_totals": {}, "column_totals": {}, "total": 0}
        labels = sorted({int(value) for value in first} | {int(value) for value in second})
        cells = Counter()
        for a, b in zip(first, second):
            cells[(int(a), int(b))] += 1
        row_totals = Counter(int(value) for value in first)
        column_totals = Counter(int(value) for value in second)
        return {
            "labels": labels,
            "cell_totals": {f"{a}|{b}": cells[(a, b)] for a in labels for b in labels},
            "row_totals": {str(key): value for key, value in sorted(row_totals.items())},
            "column_totals": {str(key): value for key, value in sorted(column_totals.items())},
            "total": total,
        }

    def _per_subject_summary(self, tasks, db: Session) -> list[Dict[str, Any]]:
        rows = OrderedDict()
        for task in tasks:
            subject_code = str((task.evidence_metadata or {}).get("subject_code") or "unlabelled")
            item = rows.setdefault(subject_code, {"subject_code": subject_code, "total": 0, "labels": [], "final": []})
            item["total"] += 1
            if task.final_alignment_label is not None:
                item["final"].append(task.final_alignment_label)
        result = []
        for subject_code, item in rows.items():
            final = item.pop("final", [])
            result.append({
                **item,
                "completed_count": len(final),
                "final_mean": round(sum(final) / len(final), 2) if final else None,
                "final_distribution": {str(key): value for key, value in sorted(Counter(final).items())},
            })
        return sorted(result, key=lambda entry: (-entry["total"], entry["subject_code"]))

    def build_sample(
        self,
        db: Session,
        actor_id: str,
        dataset_mode: str = "technical_uat_researcher_operated",
        target_size: int = 12,
        seed: Optional[str] = None,
        strata: Optional[list[str]] = None,
        assign_reviewers: Optional[list[str]] = None,
        exclude_sampled: bool = False,
    ) -> Dict[str, Any]:
        if dataset_mode not in {"technical_uat_researcher_operated", "independent_expert_validation"}:
            raise ValueError(f"Unsupported dataset mode: {dataset_mode}")
        if target_size < 2 or target_size > 500:
            raise ValueError("target_size must be between 2 and 500")
        sample_seed = seed or f"uat-researcher-sample-{date.today().isoformat()}"
        rng = random.Random(sample_seed)
        tasks = self._tasks_query(db, dataset_mode=dataset_mode).order_by(
            AlignmentReviewTask.created_at.asc()
        ).all()
        if not tasks:
            raise ValueError("No alignment review tasks exist for the requested dataset mode")
        assigned_reviewers = assign_reviewers or ["uat_analyst_01", "uat_analyst_02"]
        eligible = {}
        excluded_already_sampled = 0
        for task in tasks:
            if exclude_sampled and (task.evidence_metadata or {}).get("sample"):
                # Preserve a prior sample assignment untouched when building an
                # additional (non-disturbing) sample over newly generated tasks.
                excluded_already_sampled += 1
                continue
            if not (task.evidence_metadata or {}).get("subject_code"):
                continue
            eligible[task.task_id] = task
        if len(eligible) < target_size:
            target_size = len(eligible)
        groups = OrderedDict()
        for task in eligible.values():
            subject_code = str((task.evidence_metadata or {}).get("subject_code"))
            demand_band = self._demand_band(task.labour_market_evidence)
            key = (subject_code, demand_band)
            if strata and subject_code not in strata:
                continue
            groups.setdefault(key, []).append(task)
        if not groups:
            raise ValueError("No tasks match the requested sample strata")
        allocation = {}
        base = target_size // len(groups)
        remainder = target_size - base * len(groups)
        for index, key in enumerate(groups):
            allocation[key] = base + (1 if index < remainder else 0)
        selected: list[AlignmentReviewTask] = []
        for key, members in groups.items():
            rng.shuffle(members)
            selected.extend(members[: allocation[key]])
        rng.shuffle(selected)
        selected.sort(key=lambda task: str((task.evidence_metadata or {}).get("subject_code")))
        for index, task in enumerate(selected, start=1):
            metadata = dict(task.evidence_metadata or {})
            sample_note = {
                "sample_name": "technical_uat_researcher_operated_sample",
                "sample_seed": sample_seed,
                "sample_index": index,
                "assigned_reviewers": assigned_reviewers,
                "sampled_at": date.today().isoformat(),
                "sampling_policy": "deterministic_stratified_by_subject_and_demand_band",
            }
            metadata["sample"] = sample_note
            task.evidence_metadata = metadata
            task.sample_seed = sample_seed
            task.stratum = f"{str((task.evidence_metadata or {}).get('subject_code'))}|{self._demand_band(task.labour_market_evidence)}"
            task.dataset_mode = dataset_mode
        db.commit()
        return {
            "dataset_mode": dataset_mode,
            "sample_seed": sample_seed,
            "target_size": target_size,
            "selected_count": len(selected),
            "eligible_tasks": len(eligible),
            "excluded_already_sampled": excluded_already_sampled,
            "strata": list(groups.keys()),
            "assigned_reviewers": assigned_reviewers,
            "selected_tasks": [
                {
                    "task_id": str(task.task_id),
                    "sample_index": (task.evidence_metadata or {}).get("sample", {}).get("sample_index"),
                    "subject_code": (task.evidence_metadata or {}).get("subject_code"),
                    "stratum": task.stratum,
                    "version_id": str(task.version_id),
                    "document_id": str(task.document_id),
                    "final_alignment_label": task.final_alignment_label,
                }
                for task in selected
            ],
            "reviewer_policy": (
                "researcher_operated_uat_roles_uq58x_untrusted" if dataset_mode == "technical_uat_researcher_operated"
                else "independent_expert_validation"
            ),
            "independence_note": (
                "UAT researcher-operated accounts must document disclosure; they are not independent experts."
                if dataset_mode == "technical_uat_researcher_operated"
                else "Independent expert accounts must not have authored the sampled curriculum evidence."
            ),
        }

    @staticmethod
    def _demand_band(labour_evidence: Any) -> str:
        if not labour_evidence:
            return "no_signals"
        scores = [
            float(signal.get("demand_score") or 0.0)
            for signal in labour_evidence
            if isinstance(signal, dict) and signal.get("demand_score") is not None
        ]
        if not scores:
            return "no_scores"
        average = sum(scores) / len(scores)
        if average >= 0.7:
            return "high"
        if average >= 0.4:
            return "medium"
        return "low"

    @staticmethod
    def _reviewer_persona_for_mode(dataset_mode: Optional[str]) -> str:
        if dataset_mode == "independent_expert_validation":
            return "independent_expert"
        return "researcher_operated_uat"

    def disagreement_items(self, db: Session, dataset_mode: Optional[str] = None) -> list[Dict[str, Any]]:
        query = db.query(AlignmentReviewTask).filter(
            AlignmentReviewTask.status == "adjudication_required"
        )
        if dataset_mode:
            query = query.filter(AlignmentReviewTask.dataset_mode == dataset_mode)
        tasks = query.order_by(AlignmentReviewTask.updated_at.asc()).all()
        items = []
        for task in tasks:
            labels = db.query(AlignmentExpertLabel).filter(
                AlignmentExpertLabel.task_id == task.task_id
            ).order_by(AlignmentExpertLabel.created_at.asc()).all()
            first = next((item for item in labels if item.review_stage == "first"), None)
            second = next((item for item in labels if item.review_stage == "second"), None)
            items.append({
                "task_id": str(task.task_id),
                "dataset_mode": task.dataset_mode,
                "subject_code": (task.evidence_metadata or {}).get("subject_code"),
                "status": task.status,
                "first_review": self.label_dict(first) if first else None,
                "second_review": self.label_dict(second) if second else None,
            })
        return items

    def task_dict(
        self,
        db: Session,
        task: AlignmentReviewTask,
        labels=None,
        redact_labels: bool = False,
    ) -> Dict[str, Any]:
        labels = labels if labels is not None else (
            db.query(AlignmentExpertLabel)
            .filter(AlignmentExpertLabel.task_id == task.task_id)
            .order_by(AlignmentExpertLabel.created_at.asc())
            .all()
        )
        return {
            "task_id": str(task.task_id),
            "document_id": str(task.document_id),
            "version_id": str(task.version_id),
            "chunk_id": str(task.chunk_id) if task.chunk_id else None,
            "status": task.status,
            "dataset_mode": task.dataset_mode,
            "stratum": task.stratum,
            "sample_seed": task.sample_seed,
            "curriculum_evidence": task.curriculum_evidence,
            "labour_market_evidence": task.labour_market_evidence or [],
            "evidence_metadata": task.evidence_metadata or {},
            "final_alignment_label": task.final_alignment_label,
            "labels": (
                [
                    {
                        "review_stage": label.review_stage,
                        "submitted": True,
                        "decision_hidden": True,
                    }
                    for label in labels
                ]
                if redact_labels
                else [self.label_dict(label) for label in labels]
            ),
            "created_at": task.created_at.isoformat() if task.created_at else None,
        }

