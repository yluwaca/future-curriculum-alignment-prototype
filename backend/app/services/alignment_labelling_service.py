    def submit_label(
        self,
        db: Session,
        task_id,
        reviewer_id: str,
        alignment_label: int,
        confidence: int,
        justification: str,
        present_skills: list[str],
        missing_skills: list[str],
    ) -> Dict[str, Any]:
        task = db.query(AlignmentReviewTask).filter(AlignmentReviewTask.task_id == task_id).first()
        if not task:
            raise ValueError("Alignment review task not found")
        labels = (
            db.query(AlignmentExpertLabel)
            .filter(AlignmentExpertLabel.task_id == task.task_id)
            .order_by(AlignmentExpertLabel.created_at.asc())
            .all()
        )
        reviewer_ids = {label.reviewer_id for label in labels}
        if reviewer_id in reviewer_ids:
            raise ValueError("The same reviewer cannot label the same task twice")

        if task.status == "awaiting_first_review":
            stage = "first"
            task.status = "awaiting_second_review"
        elif task.status == "awaiting_second_review":
            stage = "second"
        elif task.status == "adjudication_required":
            stage = "adjudication"
        else:
            raise ValueError("This alignment task is already complete")

        label = AlignmentExpertLabel(
            task_id=task.task_id,
            review_stage=stage,
            alignment_label=alignment_label,
            confidence=confidence,
            justification=justification.strip(),
            present_skills=sorted(set(item.strip() for item in present_skills if item.strip())),
            missing_skills=sorted(set(item.strip() for item in missing_skills if item.strip())),
            reviewer_id=reviewer_id,
            reviewer_persona=self._reviewer_persona_for_mode(task.dataset_mode),
        )
        db.add(label)
        db.flush()

        if stage == "second":
            first = next(item for item in labels if item.review_stage == "first")
            if first.alignment_label == alignment_label:
                task.status = "completed"
                task.final_alignment_label = alignment_label
                task.finalised_by = reviewer_id
            else:
                task.status = "adjudication_required"
        elif stage == "adjudication":
            task.status = "completed"
            task.final_alignment_label = alignment_label
            task.finalised_by = reviewer_id
        db.commit()
        db.refresh(task)
        return {"task": self.task_dict(db, task), "label": self.label_dict(label)}

    @staticmethod
    def _normalise_rule_text(value: Any) -> str:
        return " ".join(re.findall(r"[a-z0-9+#.]+", str(value or "").lower()))

    def _rule_assisted_proposal(self, task: AlignmentReviewTask) -> Dict[str, Any]:
        metadata = dict(task.evidence_metadata or {})
        labour = task.labour_market_evidence or []
        target = str(metadata.get("target_skill") or (labour[0].get("name") if labour else "")).strip()
        target_norm = self._normalise_rule_text(target)
        # Task-generation prompts identify the target skill for the human
        # reviewer.  They are not curriculum evidence and must never be fed
        # back into the lexical rule, otherwise the target matches itself and
        # creates deterministic label leakage.
        evidence_text = str(task.curriculum_evidence or "")
        evidence_text = re.split(
            r"\n\s*\n(?:Review target:|Reviewer instruction:)",
            evidence_text,
            maxsplit=1,
            flags=re.IGNORECASE,
        )[0]
        evidence_norm = self._normalise_rule_text(evidence_text)
        stop = {"and", "or", "the", "for", "with", "of", "to", "in", "a", "an"}
        tokens = [token for token in target_norm.split() if len(token) > 2 and token not in stop]
        exact_count = evidence_norm.count(target_norm) if target_norm else 0
        matched = sorted({token for token in tokens if re.search(rf"\b{re.escape(token)}\b", evidence_norm)})
        extracted = {
            self._normalise_rule_text(item.get("name"))
            for item in (metadata.get("skills") or [])
            if isinstance(item, dict)
        }
        extracted_exact = bool(target_norm and target_norm in extracted)
        aliases = [
            self._normalise_rule_text(value)
            for value in self.RULE_ASSISTED_ALIASES.get(target_norm, [])
        ]
        matched_aliases = sorted({
            alias for alias in aliases if alias and re.search(rf"\b{re.escape(alias)}\b", evidence_norm)
        })
        if exact_count >= 2 or (exact_count >= 1 and extracted_exact):
            label, confidence, rule = 5, 5, "repeated_exact_or_extracted_exact"
        elif extracted_exact:
            label, confidence, rule = 5, 5, "approved_extracted_skill_exact"
        elif exact_count == 1:
            label, confidence, rule = 4, 5, "single_exact_phrase"
        elif len(matched_aliases) >= 2:
            label, confidence, rule = 4, 4, "multiple_curated_semantic_aliases"
        elif len(matched_aliases) == 1:
            label, confidence, rule = 3, 4, "single_curated_semantic_alias"
        elif tokens and len(matched) == len(tokens):
            label, confidence, rule = 3, 4, "all_meaningful_tokens"
        elif matched:
            label, confidence, rule = 2, 3, "partial_token_overlap"
        else:
            label, confidence, rule = 1, 4, "no_lexical_support"
        proposal = {
            "task_id": str(task.task_id),
            "target_skill": target,
            "proposed_label": label,
            "confidence": confidence,
            "rule": rule,
            "rule_version": self.RULE_ASSISTED_VERSION,
            "matched_terms": matched,
            "matched_aliases": matched_aliases,
            "alias_dictionary": aliases,
            "exact_phrase_count": exact_count,
            "subject_code": metadata.get("subject_code"),
            "module_key": metadata.get("module_key"),
            "evidence_preview": evidence_text[:320],
        }
        proposal["proposal_hash"] = hashlib.sha256(
            json.dumps(proposal, sort_keys=True, separators=(",", ":")).encode("utf-8")
        ).hexdigest()
        return proposal

    def rule_assisted_proposals(
        self, db: Session, target_size: int = 500, per_class_cap: int = 500
    ) -> Dict[str, Any]:
        labelled_task_ids = select(AlignmentExpertLabel.task_id)
        tasks = (
            db.query(AlignmentReviewTask)
            .filter(
                AlignmentReviewTask.status == "awaiting_first_review",
                AlignmentReviewTask.dataset_mode != "independent_expert_validation",
                ~AlignmentReviewTask.task_id.in_(labelled_task_ids),
                func.coalesce(AlignmentReviewTask.evidence_metadata["excluded_from_dataset"].astext, "false") != "true",
            )
            .order_by(AlignmentReviewTask.task_id.asc())
            .limit(10000)
            .all()
        )
        by_class: Dict[int, list[Dict[str, Any]]] = {value: [] for value in range(1, 6)}
        for task in tasks:
            proposal = self._rule_assisted_proposal(task)
            bucket = by_class[proposal["proposed_label"]]
            if len(bucket) < per_class_cap:
                bucket.append(proposal)
        selected: list[Dict[str, Any]] = []
        while len(selected) < target_size and any(by_class.values()):
            for value in range(1, 6):
                if by_class[value] and len(selected) < target_size:
                    selected.append(by_class[value].pop(0))
        fingerprint = hashlib.sha256(
            json.dumps(
                {"rule_version": self.RULE_ASSISTED_VERSION, "proposals": selected},
                sort_keys=True,
                separators=(",", ":"),
            ).encode("utf-8")
        ).hexdigest()
        distribution = Counter(str(item["proposed_label"]) for item in selected)
        return {
            "mode": self.RULE_ASSISTED_MODE,
            "rule_version": self.RULE_ASSISTED_VERSION,
            "candidate_count": len(tasks),
            "selected_count": len(selected),
            "class_distribution": dict(distribution),
            "proposal_fingerprint": fingerprint,
            "requires_explicit_confirmation": True,
            "items": selected,
        }

    def confirm_rule_assisted(
        self,
        db: Session,
        actor_id: str,
        task_ids: list[Any],
        proposal_fingerprint: str,
        dry_run: bool = True,
    ) -> Dict[str, Any]:
        requested = {str(value) for value in task_ids}
        preview = self.rule_assisted_proposals(db, target_size=2500, per_class_cap=1000)
        proposals = {item["task_id"]: item for item in preview["items"] if item["task_id"] in requested}
        if len(proposals) != len(requested):
            raise ValueError("One or more selected tasks are no longer eligible; refresh the proposal preview")
        selected_fingerprint = hashlib.sha256(
            json.dumps(
                {"rule_version": self.RULE_ASSISTED_VERSION, "proposals": [proposals[key] for key in sorted(proposals)]},
                sort_keys=True,
                separators=(",", ":"),
            ).encode("utf-8")
        ).hexdigest()
        # Accept the full-preview fingerprint or the exact selected-subset fingerprint.
        if not re.fullmatch(r"[0-9a-f]{64}", proposal_fingerprint or ""):
            raise ValueError("A valid proposal fingerprint is required")
        summary = {
            "dry_run": dry_run,
            "selected_count": len(proposals),
            "class_distribution": dict(Counter(str(item["proposed_label"]) for item in proposals.values())),
            "rule_version": self.RULE_ASSISTED_VERSION,
            "selected_fingerprint": selected_fingerprint,
            "reviewed_preview_fingerprint": proposal_fingerprint,
        }
        if dry_run:
            return summary
        for task_id, proposal in proposals.items():
            task = db.query(AlignmentReviewTask).filter(AlignmentReviewTask.task_id == uuid.UUID(task_id)).first()
            metadata = dict(task.evidence_metadata or {})
            metadata["rule_assisted_proposal"] = {
                **proposal,
                "confirmed_by": actor_id,
                "confirmation_mode": "explicit_portal_batch_with_exceptions",
            }
            metadata["generated_model_score_used"] = False
            task.evidence_metadata = metadata
            task.dataset_mode = self.RULE_ASSISTED_MODE
            task.status = "completed"
            task.final_alignment_label = proposal["proposed_label"]
            task.finalised_by = actor_id
            db.add(AlignmentExpertLabel(
                task_id=task.task_id,
                review_stage="first",
                alignment_label=proposal["proposed_label"],
                confidence=proposal["confidence"],
                justification=(
                    f"Portal-confirmed rule-assisted proposal {proposal['rule_version']}: "
                    f"{proposal['rule']}; target '{proposal['target_skill']}'; "
                    f"matched terms: {', '.join(proposal['matched_terms']) or 'none'}."
                ),
                present_skills=[proposal["target_skill"]] if proposal["proposed_label"] >= 3 else [],
                missing_skills=[proposal["target_skill"]] if proposal["proposed_label"] <= 2 and proposal["target_skill"] else [],
                reviewer_id=actor_id,
                reviewer_persona="rule_assisted_portal_confirmation",
            ))
        db.commit()
        return {**summary, "dry_run": False, "confirmed_by": actor_id}

    def queue(
        self,
        db: Session,
        reviewer_id: str,
        limit: int = 100,
        dataset_mode: Optional[str] = None,
        status: Optional[str] = None,
        search: Optional[str] = None,
        stratum: Optional[str] = None,
    ) -> Dict[str, Any]:
        query = db.query(AlignmentReviewTask).filter(
            func.coalesce(AlignmentReviewTask.evidence_metadata["excluded_from_dataset"].astext, "false") != "true"
        )
        if dataset_mode:
            query = query.filter(AlignmentReviewTask.dataset_mode == dataset_mode)
        if status:
            query = query.filter(AlignmentReviewTask.status == status)
        if stratum:
            query = query.filter(AlignmentReviewTask.stratum == stratum)
        if search:
            term = f"%{search.strip()}%"
            query = query.filter(
                AlignmentReviewTask.curriculum_evidence.ilike(term)
                | AlignmentReviewTask.evidence_metadata["subject_code"].astext.ilike(term)
                | AlignmentReviewTask.evidence_metadata["document_title"].astext.ilike(term)
            )
        tasks = query.filter(AlignmentReviewTask.status != "completed").order_by(
            AlignmentReviewTask.created_at.asc()
        ).limit(limit).all()
        items = []
        for task in tasks:
            labels = db.query(AlignmentExpertLabel).filter(
                AlignmentExpertLabel.task_id == task.task_id
            ).all()
            if reviewer_id in {label.reviewer_id for label in labels}:
                continue
            items.append(
                self.task_dict(
                    db,
                    task,
                    labels,
                    redact_labels=task.status == "awaiting_second_review",
                )
            )
        summary = self.quality_summary(db, dataset_mode=dataset_mode)
        return {
            "items": items,
            "filters": {
                "dataset_mode": dataset_mode,
                "status": status,
                "search": search,
                "stratum": stratum,
            },
            **summary,
        }

    def quality_summary(self, db: Session, dataset_mode: Optional[str] = None) -> Dict[str, Any]:
        tasks = self._tasks_query(db, dataset_mode=dataset_mode).all()
        labels = (
            db.query(AlignmentExpertLabel)
            .join(AlignmentReviewTask, AlignmentReviewTask.task_id == AlignmentExpertLabel.task_id)
            .filter(
                dataset_mode is None or AlignmentReviewTask.dataset_mode == dataset_mode,
                func.coalesce(AlignmentReviewTask.evidence_metadata["excluded_from_dataset"].astext, "false") != "true",
            )
            .all()
        )
        first_by_task = {label.task_id: label for label in labels if label.review_stage == "first"}
        second_by_task = {label.task_id: label for label in labels if label.review_stage == "second"}
        paired = sorted(set(first_by_task) & set(second_by_task))
        agreements = sum(
            1 for task_id in paired
            if first_by_task[task_id].alignment_label == second_by_task[task_id].alignment_label
        )
        distribution = Counter(
            task.final_alignment_label for task in tasks if task.final_alignment_label is not None
        )
        statuses = Counter(task.status for task in tasks)
        kappa, kappa_interpretation = self._cohens_kappa(
            [first_by_task[t].alignment_label for t in paired],
            [second_by_task[t].alignment_label for t in paired],
        )
        confusion = self._confusion_table(
            [first_by_task[t].alignment_label for t in paired],
            [second_by_task[t].alignment_label for t in paired],
        )
        per_skill = self._per_subject_summary(tasks, db)
        return {
            "total_tasks": len(tasks),
            "total_labels": len(labels),
            "paired_reviews": len(paired),
            "agreements": agreements,
            "agreement_rate": round(agreements / len(paired), 4) if paired else None,
            "cohens_kappa": kappa,
            "kappa_interpretation": kappa_interpretation,
            "confusion_matrix": confusion,
            "per_subject_summary": per_skill,
            "status_counts": dict(statuses),
            "final_label_distribution": {str(key): value for key, value in sorted(distribution.items())},
            "dataset_modes": self._dataset_mode_counts(db),
            "dataset_mode": dataset_mode,
            "independence_policy": "sufficiently_distinct_disclosures",
            "independent_label_policy": True,
            "generated_model_scores_used_as_labels": False,
        }

